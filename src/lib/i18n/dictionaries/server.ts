export function getServerDict(locale: Locale) { return locale === "en" ? en : ptBR; }

const dynamicMessages = Object.keys(ptBR).filter(key => /\{\d+\}/.test(key)).map(key => {
  const slots: number[] = [];
  const pattern = key.split(/(\{\d+\})/).map(part => {
    if (/^\{\d+\}$/.test(part)) { slots.push(Number(part.slice(1, -1))); return "(.*?)"; }
    return part.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  }).join("");
  return { key, slots, pattern: new RegExp(`^${pattern}$`, "s") };
});

/** Interpolate only explicit slots; user values are never interpreted as dictionary keys. */
export function translateServer(locale: Locale, key: string, ...values: unknown[]): string {
  if (/^(?:Invalid (?:input|option|string|email|URL|UUID|date)|Too (?:small|big):)/.test(key)) {
    return locale === "en" ? "Check the fields." : "Confira os campos.";
  }
  const dictionary: Record<string, string> = getServerDict(locale);
  if (locale === "en" && !values.length && !Object.hasOwn(dictionary, key)) {
    for (const candidate of dynamicMessages) {
      const match = candidate.pattern.exec(key);
      if (!match) continue;
      const captured: string[] = [];
      candidate.slots.forEach((slot, index) => { captured[slot] = match[index + 1]; });
      return translateServer(locale, candidate.key, ...captured);
    }
  }
  const template = Object.prototype.hasOwnProperty.call(dictionary, key) ? dictionary[key] : key;
  return template.replace(/\{(\d+)\}/g, (slot, index) => Number(index) < values.length ? String(values[Number(index)]) : slot);
}
