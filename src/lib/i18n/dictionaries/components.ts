/** Unknown text comes from callers or user data and is preserved verbatim. */
function createTranslator(dictionary: Readonly<Record<string, string>>) {
  return (key: string, values: Record<string, string | number> = {}) => {
    const text = Object.hasOwn(dictionary, key) ? dictionary[key] : key;
    return text.replace(/\{(\w+)\}/g, (placeholder, name: string) =>
      Object.hasOwn(values, name) ? String(values[name]) : placeholder);
  };
}


const translators = { "pt-BR": createTranslator(ptBR), en: createTranslator(en) };
export function getComponentsTranslator(locale: Locale) { return translators[locale]; }
