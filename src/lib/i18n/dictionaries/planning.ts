export function getPlanningDict(locale: Locale) { return locale === "en" ? en : ptBR; }

/** Interpolate only explicit slots; user values are never interpreted as dictionary keys. */
export function translatePlanning(locale: Locale, key: string, ...values: unknown[]): string {
  const dictionary: Record<string, string> = getPlanningDict(locale);
  const template = Object.prototype.hasOwnProperty.call(dictionary, key) ? dictionary[key] : key;
  return template.replace(/\{(\d+)\}/g, (slot, index) => Number(index) < values.length ? String(values[Number(index)]) : slot);
}
